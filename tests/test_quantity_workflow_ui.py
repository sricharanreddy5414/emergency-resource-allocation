"""Frontend quantity workflow: request resource dropdown and inventory display."""

import shutil
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def node_executable():
    found = shutil.which("node")
    if found:
        return found
    portable = Path(r"C:\Users\sri charan reddy\AppData\Local\Temp\erap-node\node-v22.20.0-win-x64\node.exe")
    if portable.is_file():
        return str(portable)
    return None


def test_quantity_workflow_ui():
    node = node_executable()
    assert node, "Node is required to execute the quantity workflow UI test"
    result = subprocess.run(
        [node, str(ROOT / "tests" / "quantity_workflow_ui.mjs")],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    assert "quantity workflow ui passed" in result.stdout
